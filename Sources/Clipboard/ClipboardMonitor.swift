import AppKit
import ImageIO

/// 轮询系统剪贴板（changeCount 变化才读取），捕获文本 / 图片 / 文件。
final class ClipboardMonitor {
    var isPaused: Bool = false
    var onCapture: ((ClipboardStore.Item) -> Void)?

    private let store = ClipboardStore.shared
    private var timer: Timer?
    private var lastChangeCount: Int = -1
    private var ownChangeCount: Int = -1

    var maxImageBytes: Int = 10 * 1024 * 1024
    var skipSensitive: Bool = true

    func start(interval: Double) {
        stop()
        lastChangeCount = NSPasteboard.general.changeCount
        let timer = Timer(timeInterval: max(0.2, interval), repeats: true) { [weak self] _ in
            self?.tick()
        }
        RunLoop.main.add(timer, forMode: .common)
        self.timer = timer
    }

    func stop() {
        timer?.invalidate()
        timer = nil
    }

    func tick() {
        let pasteboard = NSPasteboard.general
        let changeCount = pasteboard.changeCount
        guard changeCount != lastChangeCount else { return }
        lastChangeCount = changeCount

        // 自己写回剪贴板触发的变化，忽略
        if changeCount == ownChangeCount { return }
        guard !isPaused else { return }
        capture(from: pasteboard)
    }

    func captureNow() {
        lastChangeCount = NSPasteboard.general.changeCount
        guard !isPaused else { return }
        capture(from: NSPasteboard.general)
    }

    private var debugLogging: Bool {
        ProcessInfo.processInfo.environment["CLIPSTATS_DIAG"] == "1"
    }

    private func capture(from pasteboard: NSPasteboard) {
        guard let items = pasteboard.pasteboardItems, let first = items.first else {
            if debugLogging { NSLog("%@", "capture: no pasteboard items") }
            return
        }
        let typeNames = first.types.map { $0.rawValue }
        if debugLogging { NSLog("%@", "capture: types=\(typeNames)") }

        if skipSensitive {
            let sensitive = ["org.nspasteboard.ConcealedType",
                             "org.nspasteboard.TransientType",
                             "org.nspasteboard.AutoGeneratedType"]
            if typeNames.contains(where: { sensitive.contains($0) }) { return }
        }

        let sourceApp = NSWorkspace.shared.frontmostApplication?.localizedName

        // 图片优先
        if typeNames.contains(NSPasteboard.PasteboardType.png.rawValue)
            || typeNames.contains(NSPasteboard.PasteboardType.tiff.rawValue) {
            if let png = Self.pngData(from: pasteboard, item: first) {
                guard png.count <= maxImageBytes else { return }
                let thumb = Self.thumbnail(from: png)
                if let item = store.insert(kind: .image, text: nil, data: png, thumb: thumb, sourceApp: sourceApp) {
                    onCapture?(item)
                }
                return
            }
        }

        // 文件
        if typeNames.contains(NSPasteboard.PasteboardType.fileURL.rawValue) {
            let objects = pasteboard.readObjects(forClasses: [NSURL.self], options: nil) as? [URL] ?? []
            let paths = objects.map { $0.path }.filter { !$0.isEmpty }
            if debugLogging { NSLog("%@", "capture: file branch objects=\(objects.count) paths=\(paths)") }
            if !paths.isEmpty {
                let text = paths.joined(separator: "\n")
                if let item = store.insert(kind: .files, text: text, data: nil, thumb: nil, sourceApp: sourceApp) {
                    onCapture?(item)
                }
                return
            }
        }

        // 文本
        if let string = pasteboard.string(forType: .string) {
            let trimmed = string.trimmingCharacters(in: .whitespacesAndNewlines)
            if debugLogging { NSLog("%@", "capture: text branch length=\(trimmed.count)") }
            guard !trimmed.isEmpty, trimmed.count < 200_000 else { return }
            if let item = store.insert(kind: .text, text: string, data: nil, thumb: nil, sourceApp: sourceApp) {
                onCapture?(item)
            }
            return
        }
        if debugLogging { NSLog("%@", "capture: nothing matched") }
    }

    /// 把历史条目放回剪贴板，用户随后按 ⌘V 即可粘贴
    @discardableResult
    func restore(_ item: ClipboardStore.Item) -> Bool {
        let pasteboard = NSPasteboard.general
        pasteboard.clearContents()

        switch item.kind {
        case .text:
            pasteboard.setString(item.text ?? "", forType: .string)
        case .image:
            guard let data = store.payload(id: item.id), let image = NSImage(data: data) else { return false }
            pasteboard.setData(data, forType: .png)
            if let tiff = image.tiffRepresentation {
                pasteboard.setData(tiff, forType: .tiff)
            }
        case .files:
            let paths = (item.text ?? "").split(separator: "\n").map(String.init)
            let urls = paths.map { URL(fileURLWithPath: $0) as NSURL }
            if !urls.isEmpty {
                pasteboard.writeObjects(urls)
            }
        }

        ownChangeCount = pasteboard.changeCount
        lastChangeCount = pasteboard.changeCount
        store.touch(id: item.id)
        return true
    }

    // MARK: - 图片处理

    private static func pngData(from pasteboard: NSPasteboard, item: NSPasteboardItem) -> Data? {
        if let png = item.data(forType: .png) ?? pasteboard.data(forType: .png) {
            return png
        }
        guard let tiff = item.data(forType: .tiff) ?? pasteboard.data(forType: .tiff),
              let rep = NSBitmapImageRep(data: tiff) else { return nil }
        return rep.representation(using: .png, properties: [:])
    }

    private static func thumbnail(from png: Data, maxPixelSize: Int = 192) -> Data? {
        guard let source = CGImageSourceCreateWithData(png as CFData, nil) else { return nil }
        let options: [CFString: Any] = [
            kCGImageSourceCreateThumbnailFromImageAlways: true,
            kCGImageSourceCreateThumbnailWithTransform: true,
            kCGImageSourceThumbnailMaxPixelSize: maxPixelSize,
        ]
        guard let thumbnail = CGImageSourceCreateThumbnailAtIndex(source, 0, options as CFDictionary) else {
            return nil
        }
        let rep = NSBitmapImageRep(cgImage: thumbnail)
        return rep.representation(using: .png, properties: [:])
    }
}
